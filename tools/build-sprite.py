"""Builds src/components/Sprite.astro from the traced logo path.
Run: python3 tools/build-sprite.py
Splits the logo into: left foot, right foot, the 'bff' letters, and the wordmark.
"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = (root / 'tools' / 'logo-path.txt').read_text().strip()
subs = [s.strip() for s in re.split(r'(?=M)', d) if s.strip()]

def nums(s): return [float(x) for x in re.findall(r'-?\d+(?:\.\d+)?', s)]
def bbox(s):
    n = nums(s); xs, ys = n[0::2], n[1::2]
    return min(xs), min(ys), max(xs), max(ys)
def shift(s, dx, dy):
    # all commands used (M, C, L) carry absolute x,y pairs
    out, i = [], 0
    def rep(m):
        nonlocal i
        v = float(m.group(0)); r = v - (dx if i % 2 == 0 else dy); i += 1
        return ('%.1f' % r).rstrip('0').rstrip('.')
    return re.sub(r'-?\d+(?:\.\d+)?', rep, s)

word, mark = [], []
for s in subs:
    (word if bbox(s)[1] > 850 else mark).append(s)
feetL, feetR, letters = [], [], []
for s in mark:
    x0, y0, x1, y1 = bbox(s)
    cx = (x0 + x1) / 2
    if cx > 940: feetR.append(s)
    elif cx > 800: feetL.append(s)
    else: letters.append(s)
print('letters', len(letters), 'footL', len(feetL), 'footR', len(feetR), 'word', len(word))

def group(L):
    bs = [bbox(s) for s in L]
    x0 = min(b[0] for b in bs); y0 = min(b[1] for b in bs)
    x1 = max(b[2] for b in bs); y1 = max(b[3] for b in bs)
    dd = ' '.join(shift(s, x0, y0) + ' Z' for s in L)
    return dd, round(x1 - x0, 1), round(y1 - y0, 1)

fl, flw, flh = group(feetL)
fr, frw, frh = group(feetR)
closeall = lambda L: ' '.join(s + ' Z' for s in L)
dm = closeall(mark); dw = closeall(word)

astro = f'''---
// Generated by tools/build-sprite.py from the traced logo. Do not edit by hand.
---
<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">
  <defs>
    <linearGradient id="bff-grad" gradientUnits="userSpaceOnUse" x1="-332.9" y1="263.4" x2="444.9" y2="-352.1">
      <stop offset="0" style="stop-color:var(--g0)"/>
      <stop offset="0.3" style="stop-color:var(--g1)"/>
      <stop offset="0.6" style="stop-color:var(--g2)"/>
      <stop offset="1" style="stop-color:var(--g3)"/>
    </linearGradient>
    <symbol id="foot-l" viewBox="0 0 {flw} {flh}"><path fill="currentColor" fill-rule="evenodd" d="{fl}"/></symbol>
    <symbol id="foot-r" viewBox="0 0 {frw} {frh}"><path fill="currentColor" fill-rule="evenodd" d="{fr}"/></symbol>
    <symbol id="bff-mark" viewBox="140 270 990 580"><g fill="url(#bff-grad)" fill-rule="evenodd"><path d="{dm}"/></g></symbol>
    <symbol id="bff-lockup" viewBox="140 270 990 675"><g fill="url(#bff-grad)" fill-rule="evenodd"><path d="{dm}"/><path d="{dw}"/></g></symbol>
  </defs>
</svg>
'''
(root / 'src' / 'components' / 'Sprite.astro').write_text(astro)
print('foot-l viewBox', flw, flh, ' foot-r viewBox', frw, frh, 'bytes', len(astro))

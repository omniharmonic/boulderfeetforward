#!/usr/bin/env python3
"""Generates src/components/HeroScene.astro (Flatirons line art). Edit the numbers below and re-run:
   python3 tools/build-hero.py
Designed by Benjamin Life (@omniharmonic) as a gift to Boulder Feet Forward."""
import re, pathlib
W, H = 1200, 620      # drawing size
G = 560               # ground line (y)
K = 1.25              # how much taller the mountains are than the original sketch
def Y(y, k=None):  # stretch y (original ground was 372) up from the new ground line
    return G - (372 - y) * (K if k is None else k)

def stretch(d, k=None):
    """Re-map every absolute y coordinate in a path made of M/L/C commands (no relative cmds)."""
    toks = re.findall(r'[MLCSAmlcsa]|-?\d+\.?\d*', d)
    out, i = [], 0
    cmd = None
    nums = []
    def flush():
        nonlocal nums
        if cmd and nums:
            pairs = [(nums[j], nums[j+1]) for j in range(0, len(nums), 2)]
            out.append(cmd + ' ' + ' '.join(f'{x:g} {Y(y, k):.1f}' for x, y in pairs))
        nums = []
    for t in toks:
        if t.isalpha():
            flush(); cmd = t
        else:
            nums.append(float(t))
    flush()
    return ' '.join(out)

def P(d, cls='', delay=0):
    return f'<path class="draw {cls}" pathLength="1" d="{d}" style="--d:{delay}"/>'

parts = []
# far ridge (Front Range), faint, gradient
parts.append(P(stretch("M-900 330 L0 330 C 90 300, 150 312, 230 286 C 300 262, 380 236, 470 262 C 540 282, 600 200, 700 214 C 780 226, 860 170, 960 198 C 1040 220, 1120 180, 1200 210 L2100 210", 0.8), 'grad faint', .2))
# five Flatirons drawn as one ridge profile: a steep cliff up, a long smooth face down, repeat.
# Because it is one line, nothing crosses. (x of each peak, rise in original units)
peaks = [(596, 118), (726, 205), (856, 290), (986, 196), (1116, 130)]
SW = 130
valley = 52
d = f"M572 372 C 580 372, 586 {372-30}, 596 {372-118}"
hatch_paths = []
for i, (px, rise) in enumerate(peaks):
    py = 372 - rise
    nx = px + SW - 20   # the valley sits a little left of the next peak, so each cliff leans
    vy = 372 - valley
    last = i == len(peaks) - 1
    endy = 372 if last else vy
    d += f" C {px+36} {py+rise*0.26:.0f}, {nx-34 if not last else nx-20} {endy-(endy-py)*0.15:.0f}, {nx if not last else 1200} {endy}"
    if not last:
        npx, nrise = peaks[i+1]
        d += f" L {npx} {372-nrise}"
    ticks = []
    for f in (0.34, 0.56, 0.78):
        tx = px + 22 + (SW - 40) * f * 0.7
        ty = py + (endy - py) * f * 0.8 + 6
        ticks.append((tx, ty, tx + 14, ty + 6))
    hatch_paths.append(' '.join(f'M{x0:.0f} {Y(y0):.1f} L{x1:.0f} {Y(y1):.1f}' for x0, y0, x1, y1 in ticks))
parts.append(P(stretch(d), '', .5))
# sun
parts.append(P("M1000 70 a 38 38 0 1 1 76 0 a 38 38 0 1 1 -76 0", 'sun', .1))
# ground
parts.append(P(f"M-900 {G} L0 {G} C 120 {G-12}, 180 {G+8}, 300 {G} C 420 {G-8}, 520 {G-16}, 640 {G} C 780 {G+14}, 940 {G+12}, 1200 {G} L2100 {G}", '', 0))
# pines
def pine(x, y, s, d):
    h, w = 96 * s, 34 * s
    return P(f"M{x} {y} v{-h*.18:.1f} M{x} {y-h*.18:.1f} l{-w*.5:.1f} 0 l{w*.5:.1f} {-h*.34:.1f} l{-w*.36:.1f} 0 l{w*.36:.1f} {-h*.3:.1f} l{-w*.2:.1f} 0 l{w*.2:.1f} {-h*.3:.1f} l{w*.2:.1f} {h*.3:.1f} l{-w*.2:.1f} 0 l{w*.36:.1f} {h*.3:.1f} l{-w*.36:.1f} 0 l{w*.5:.1f} {h*.34:.1f} z", 'leaf', d)
for x, dy, s, d in [(478,0,.62,1.6),(446,5,.4,1.7)]:
    parts.append(pine(x, G + dy, s, d))
# footprints walking across, heading right
walk = []
for i in range(9):
    x = 70 + i * 58
    y = G + 30 + (10 if i % 2 else -2)
    foot = 'r' if i % 2 else 'l'
    ratio = (162.4 / 325.3) if foot == 'r' else (136.2 / 311.3)
    fh = 34; fw = fh * ratio
    walk.append(f'<g transform="translate({x} {y}) rotate(90)"><use class="walker" style="--i:{i}" href="#foot-{foot}" x="{-fw/2:.1f}" y="{-fh/2:.1f}" width="{fw:.1f}" height="{fh}" /></g>')

svg = f'''---
// Flatirons line art, drawn on load. Generated by tools/build-hero.py, so change the numbers there.
---
<div class="scene" aria-hidden="true">
  <svg viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax meet" role="presentation" style="overflow:visible">
    <defs>
      <linearGradient id="ridge-grad" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="1200" y2="0">
        <stop offset="0" style="stop-color:var(--g0)" /><stop offset="0.5" style="stop-color:var(--g2)" /><stop offset="1" style="stop-color:var(--g3)" />
      </linearGradient>
    </defs>
    {''.join(parts)}
    {''.join(walk)}
  </svg>
</div>
'''
pathlib.Path(__file__).resolve().parent.parent.joinpath('src/components/HeroScene.astro').write_text(svg)
print('wrote HeroScene.astro', len(svg), 'bytes')
